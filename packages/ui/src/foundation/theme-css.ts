import {
  accent, action, bg, brand, ease, elevation, font, fg, line, motion, radius, space, status, text, width,
} from './tokens.js';

type Theme = 'light' | 'dark';

function colors(t: Theme): [string, string][] {
  const out: [string, string][] = [];
  for (const [k, v] of Object.entries(bg[t])) out.push([`bg-${k}`, v]);
  for (const [k, v] of Object.entries(fg[t])) out.push([`fg-${k}`, v]);
  for (const [k, v] of Object.entries(accent[t])) out.push([k === 'base' ? 'accent' : `accent-${k}`, v]);
  for (const [k, v] of Object.entries(action[t])) out.push([k === 'base' ? 'action' : `action-${k}`, v]);
  for (const [k, v] of Object.entries(line[t])) out.push([`line-${k}`, v]);
  out.push(['brand', brand[t].base]);
  for (const [tone, themes] of Object.entries(status)) {
    for (const [k, v] of Object.entries(themes[t])) out.push([k === 'base' ? `status-${tone}` : `status-${tone}-${k}`, v]);
  }
  for (const [k, v] of Object.entries(elevation[t])) out.push([`elevation-${k}`, v]);
  return out;
}

function decls(entries: [string, string][], indent: string): string {
  return entries.map(([k, v]) => `${indent}--ax-${k}: ${v};`).join('\n');
}

export function renderThemeCss(): string {
  const plain: [string, string][] = [];
  for (const [k, v] of Object.entries(space)) plain.push([`space-${k}`, v]);
  for (const [k, v] of Object.entries(radius)) plain.push([`radius-${k}`, v]);
  for (const [k, v] of Object.entries(motion)) plain.push([`motion-${k}`, v]);
  plain.push(['motion-ease', ease]);
  for (const [k, v] of Object.entries(width)) plain.push([`width-${k}`, v]);
  for (const [role, r] of Object.entries(text)) {
    plain.push([`text-${role}-size`, r.size], [`text-${role}-line`, r.line], [`text-${role}-weight`, String(r.weight)]);
    plain.push([`text-${role}-font`, `var(--ax-font-${r.font})`]);
  }
  plain.push(['font-sans', font.sans], ['font-mono', font.mono]);

  return [
    '/* Generated by scripts/gen-theme.ts from src/foundation/tokens.ts. Do not edit; run pnpm --filter @project-ax/ui gen. */',
    ':root {',
    '  color-scheme: light;',
    decls(colors('light'), '  '),
    decls(plain, '  '),
    '}',
    '',
    '@media (prefers-color-scheme: dark) {',
    "  :root:not([data-theme='light']) {",
    '    color-scheme: dark;',
    decls(colors('dark'), '    '),
    '  }',
    '}',
    '',
    ":root[data-theme='dark'] {",
    '  color-scheme: dark;',
    decls(colors('dark'), '  '),
    '}',
    '',
  ].join('\n');
}
